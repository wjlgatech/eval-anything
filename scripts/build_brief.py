#!/usr/bin/env python3
"""build_brief.py — GENERATE brief/data.js from data/*.yml (single source of truth).

The brief webapp's UI AND its copilot corpus both read this one file, so they can
never drift from the repo's data. `--check` = drift gate (fails when the committed
data.js differs from the regenerated one). Never hand-edit brief/data.js.
Pattern: graph-engineering-anything scripts/build_brief.py (family reference).
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def load(name):
    p = ROOT / "data" / name
    return yaml.safe_load(p.read_text()) if p.exists() else None


def render() -> str:
    meta = load("meta.yml")
    registry = load("registry.yml") or []
    papers = load("papers.yml") or []
    oec = load("oec.yml") or []
    labs = load("labs.yml") or []
    blogs = load("blogs.yml") or []
    people = load("people.yml") or []
    security = load("security.yml") or []
    examples = load("examples.yml") or []
    news = load("news.yml") or []

    corpus = [f"{meta['title']} — {meta['tagline']}. {meta['description'].strip()}"]
    for k, v in meta["folds"].items():
        corpus.append(f"The {k} fold: {v}")
    for st in meta["loop"]["stages"]:
        corpus.append(f"Loop stage '{st['name']}': {st['promise']}.")
    corpus.append(
        "The OEC mental model: Observe → Evaluate → Control. Observability precedes eval "
        "(you cannot evaluate what you cannot observe — Kalman 1960 proved O and C are duals). "
        "Eval targets the objective, engineering AND business (Kohavi's OEC — Overall Evaluation "
        "Criterion — is the formalized business E). Eval without control is a scoreboard.")
    for u in registry:
        corpus.append(
            f"Tracked repo {u['repo']} [{u.get('category','')}]: {u['why']}. "
            f"Stars {u.get('stars', 'not yet synced')}, last push {(u.get('pushed_at') or 'n/a')[:10]}.")
    for p in papers:
        corpus.append(f"Seminal paper [{p['category']}]: {p['title']} ({p['cite']}). {p['why']} ({p['url']}).")
    for o in oec:
        corpus.append(f"OEC canon [{o['pillar']} / {o['horizon']}]: {o['name']} ({o['origin']}) — {o['what']}. Why load-bearing: {o['why']}.")
    for l in labs:
        corpus.append(f"Lab/org [{l['category']}]: {l['name']} — {l['what']}. Why: {l['why']}. Flagship: {l['flagship']}.")
    for b in blogs:
        corpus.append(f"Canonical post [{b['category']}]: {b['author']}, \"{b['title']}\" ({b['year']}) — {b['why']}.")
    for p in people:
        corpus.append(f"Person [{p['category']}]: {p['name']} ({p['affiliation']}) — {p['known_for']}. Why future-making: {p['why']}.")
    for s in security:
        corpus.append(f"Security fold [{s['category']}]: {s['name']} — {s['what']}. Why: {s['why']}.")
    for f in examples:
        for e in f["examples"]:
            corpus.append(f"Super-tool feature '{f['feature']}' — say: \"{e['say']}\" → you get: {e['get']}.")
    for n in news:
        corpus.append(f"News {n['date']}: {n['entry']}")
    corpus.append("Non-negotiables: no LLM-judge score counts without a stated bias mitigation "
                  "(position/verbosity/self-preference are measured effects, Zheng et al. 2306.05685); "
                  "every reported score names benchmark VERSION + contamination status; "
                  "an honest ❌ beats a fake ✅.")
    corpus.append("Verify anything: `make check` in the repo is the only truth. The registry "
                  "refreshes weekly via `make sync` (open GitHub API, human-gated PR).")

    data = {
        "meta": {k: meta[k] for k in ("name", "emoji", "title", "tagline", "description",
                                      "audience", "github", "folds", "loop")},
        "journey_url": meta.get("journey_url", ""),
        "registry": registry,
        "papers": papers,
        "oec": oec,
        "examples": examples,
        "news": news,
        "counts": {"labs": len(labs), "blogs": len(blogs), "people": len(people),
                   "security": len(security)},
        "corpus": corpus,
    }
    return ("/* GENERATED by scripts/build_brief.py from data/*.yml — DO NOT HAND-EDIT. "
            "Edit data/ and run `make brief`. Single source for the UI AND the copilot corpus. */\n"
            "const BRIEF_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n"
            "if (typeof module !== \"undefined\") module.exports = { BRIEF_DATA };\n"
            "if (typeof window !== \"undefined\") window.BRIEF_DATA = BRIEF_DATA;\n")


if __name__ == "__main__":
    out = ROOT / "brief" / "data.js"
    text = render()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != text:
            print("❌ drift: committed brief/data.js ≠ generated (run `make brief`)")
            sys.exit(1)
        print("✅ brief drift gate green")
    else:
        out.parent.mkdir(exist_ok=True)
        out.write_text(text)
        print(f"✅ wrote {out}")
